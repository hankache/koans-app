nums = [3, 1, 2]
nums.append(4)
assert_equal(nums, [3, 1, 2, 4], 'append adds to the end')
assert_equal(len(nums), 4, 'len counts the items')
assert_equal(nums.pop(), 4, 'pop removes and returns the last item')
assert_equal(sorted(nums), [1, 2, 3], 'sorted returns a new list')
assert_equal(nums, [3, 1, 2], 'and leaves the old one alone')
nums.sort()
assert_equal(nums, [1, 2, 3], 'sort changes the list itself')
assert_equal(nums + [4, 5], [1, 2, 3, 4, 5], '+ joins lists')
