assert ''.join(reversed('abc')) == 'cba', 'join with nothing between'
assert 'ab' * 3 == 'ababab', 'repeat a string'
assert 'one\ntwo'.splitlines() == ['one', 'two'], 'splitlines cuts at line breaks'
