assert 'a,b,c'.split(',') == ['a', 'b', 'c'], 'split at commas'
assert '  one  two '.split() == ['one', 'two'], 'with no argument, split at any whitespace'
assert 'a,b,c'.split(',', 1) == ['a', 'b,c'], 'at most one split'
