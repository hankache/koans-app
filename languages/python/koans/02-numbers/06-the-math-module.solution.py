import math

assert math.sqrt(16) == 4.0, 'square roots are floats'
assert math.floor(-1.5) == -2, 'floor rounds down'
assert math.ceil(1.2) == 2, 'ceil rounds up'
assert math.factorial(5) == 120, '5 × 4 × 3 × 2 × 1'
assert math.gcd(12, 18) == 6, 'the greatest common divisor'
assert math.isclose(0.1 + 0.2, 0.3), 'isclose compares floats with a tolerance'
assert round(math.pi, 4) == 3.1416, 'pi, rounded'
