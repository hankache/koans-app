# title: Conversion
# intro: `int()`, `float()` and `str()` turn values into another type. `round()` rounds halves to the even neighbour.
assert_equal(int('42'), ___, 'a string of digits to an int')
assert_equal(float('2.5'), ___, 'a string to a float')
assert_equal(int(3.99), ___, 'int() drops the fraction')
assert_equal(str(7), ___, 'a number to a string')
assert_equal(round(2.5), ___, 'a half rounds to the even neighbour')
assert_equal(int('ff', 16), ___, 'int() reads other bases too')
