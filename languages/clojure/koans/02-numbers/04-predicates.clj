;; title: Questions about numbers
;; intro: Clojure names a function that answers yes or no with a `?`: `zero?`, `pos?`, `even?`. `inc` and `dec` add and take away one.
(is (= ___ (inc 5)) "inc adds one")
(is (= ___ (dec 5)) "dec takes one away")
(is (= ___ (zero? 0)) "zero?")
(is (= ___ (pos? -1)) "pos? asks for more than zero")
(is (= ___ (odd? 7)) "odd?")
(is (= ___ (abs -3)) "abs is the distance from zero")
