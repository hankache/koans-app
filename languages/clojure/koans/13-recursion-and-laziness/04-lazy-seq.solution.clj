(defn naturals [n] (lazy-seq (cons n (naturals (inc n)))))
(defn fib ([] (fib 0 1)) ([a b] (lazy-seq (cons a (fib b (+ a b))))))
(is (= [5 6 7] (take 3 (naturals 5))) "an infinite sequence of your own")
(is (= [0 1 1 2 3 5 8] (take 7 (fib))) "Fibonacci numbers")
(def touched (atom 0))
(def lazy (map (fn [x] (swap! touched inc) x) [1 2 3]))
(is (= 0 @touched) "nothing computed yet")
(doall lazy)
(is (= 3 @touched) "doall forces every item")
