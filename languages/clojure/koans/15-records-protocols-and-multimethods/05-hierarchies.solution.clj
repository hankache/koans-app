(derive ::dog ::animal)
(derive ::cat ::animal)
(defmulti sound identity)
(defmethod sound ::animal [_] "some sound")
(defmethod sound ::cat [_] "meow")
(is (= true (isa? ::dog ::animal)) "isa? follows derive")
(is (= "some sound" (sound ::dog)) "the parent's method")
(is (= "meow" (sound ::cat)) "the most specific method wins")
(is (= #{::animal} (parents ::dog)) "parents")
