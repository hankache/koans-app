(def counter (atom 0))
(swap! counter inc)
(swap! counter + 10)
(is (= 11 @counter) "swap! applies a function, with any extra arguments")
(reset! counter 100)
(is (= 100 @counter) "reset! replaces the value")
(is (= 101 (swap! counter inc)) "swap! returns the new value")
(def todos (atom []))
(swap! todos conj "write koans")
(is (= ["write koans"] @todos) "an atom can hold any value")
