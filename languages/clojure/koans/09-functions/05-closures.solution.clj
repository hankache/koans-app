(defn adder [n] (fn [x] (+ x n)))
(def add5 (adder 5))
(is (= 8 (add5 3)) "add5 remembers its 5")
(is (= [11 12] (map (adder 10) [1 2])) "each adder has its own n")
(defn counter [] (let [n (atom 0)] (fn [] (swap! n inc))))
(def tick (counter))
(tick)
(is (= 2 (tick)) "the closure keeps its own atom")
(is (= 1 ((counter))) "and each counter has its own")
