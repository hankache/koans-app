local co = coroutine.create(function()
  coroutine.yield('ok')
  error('broken', 0)
end)
coroutine.resume(co)
assert.are.same({false, 'broken'}, {coroutine.resume(co)}, 'resume reports the error')
assert.are.equal('dead', coroutine.status(co), 'and the coroutine is over')
local gen = coroutine.wrap(function() error('wrapped', 0) end)
assert.error_matches(gen, 'wrapped', 'wrap raises it')
assert.is_true(coroutine.wrap(function() return coroutine.isyieldable() end)(), 'isyieldable: inside a coroutine, yes')
