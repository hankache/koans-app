local t = os.time({year = 2026, month = 1, day = 1, hour = 12})
local later = os.time({year = 2026, month = 1, day = 2, hour = 12})
assert.are.equal(86400, later - t, 'a day in seconds')
assert.are.equal('1970-01-01', os.date('!%Y-%m-%d', 0), 'second 0 in UTC')
assert.are.equal('Thursday', os.date('!%A', 0), 'the epoch was a Thursday')
local d = os.date('!*t', 86400 * 31)
assert.are.equal(2, d.month, '*t gives a table; day 32 of 1970 is in February')
assert.is_number(os.clock(), 'os.clock measures processor time')
