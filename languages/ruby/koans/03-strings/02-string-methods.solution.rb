expect('hello'.upcase).to eq('HELLO'), 'upper case'
expect('hello world'.capitalize).to eq('Hello world'), 'only the first letter'
expect('  trim me  '.strip).to eq('trim me'), 'strip removes surrounding spaces'
expect('ruby'.reverse).to eq('ybur'), 'reverse'
expect('banana'.count('a')).to eq(3), 'count characters'
expect('banana'.index('n')).to eq(2), 'where it first appears'
expect('hello'.sub('l', 'L')).to eq('heLlo'), 'sub replaces the first match'
expect('hello'.gsub('l', 'L')).to eq('heLLo'), 'gsub replaces them all'
expect('hello').to start_with('he'), 'start_with'
