expect(0 ? 'yes' : 'no').to eq('yes'), 'zero is true in Ruby'
expect('' ? 'yes' : 'no').to eq('yes'), 'so is the empty string'
expect(nil ? 'yes' : 'no').to eq('no'), 'nil is falsy'
expect([]).to be_truthy, 'be_truthy: anything but nil or false'
expect(!!nil).to eq(false), '!! turns a value into true or false'
expect(nil || 'default').to eq('default'), '|| gives the right side when the left is falsy'
expect(false && raise('never runs')).to eq(false), '&& stops at the first falsy value'
