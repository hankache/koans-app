expect([1, 2, 3, 4].reduce(:+)).to eq(10), 'reduce with an operator'
expect([1, 2, 3, 4].reduce(1) { |product, n| product * n }).to eq(24), 'with a start and a block'
expect(%w[a bb ccc].reduce(0) { |sum, w| sum + w.size }).to eq(6), 'any kind of total'
expect([].sum).to eq(0), 'sum of nothing'
expect([0.1, 0.2, 0.3].sum).to eq(0.6), 'sum adds floats carefully'
expect([[1, 2], [3, 4]].sum([])).to eq([1, 2, 3, 4]), 'sum can concatenate'
