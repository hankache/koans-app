test_that("unlist flattens", expect_equal(unlist(list(1, list(2, 3))), c(1, 2, 3)))
test_that("names are kept, and joined", expect_equal(unlist(list(a = 1, b = list(c = 2))), c(a = 1, b.c = 2)))
test_that("mixed types become text", expect_equal(unlist(list(1, "a")), c("1", "a")))
test_that("do.call with a list of arguments", expect_equal(do.call(paste, list("a", "b", sep = "+")), "a+b"))
test_that("do.call rbind stacks rows", expect_equal(nrow(do.call(rbind, list(1:2, 3:4, 5:6))), 3L))
