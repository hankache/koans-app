sound <- function(animal) switch(animal, cat = "meow", dog = , wolf = "woof", "...")
test_that("by name", expect_equal(sound("cat"), "meow"))
test_that("dog falls through to wolf", expect_equal(sound("dog"), "woof"))
test_that("the default", expect_equal(sound("fish"), "..."))
test_that("with a number, by position", expect_equal(switch(2, "a", "b", "c"), "b"))
