words <- c("listen", "silent", "enlist", "google", "gooegl", "cat", "act")
key <- vapply(strsplit(words, ""), function(ch) paste(sort(ch), collapse = ""), "")
by_key <- split(words, key)
test_that("sorted letters are the key", expect_equal(by_key[["eilnst"]], c("listen", "silent", "enlist")))
test_that("split names them in sorted order", expect_equal(names(by_key), c("act", "eggloo", "eilnst")))
test_that("the size of each", expect_equal(unname(lengths(by_key)), c(2L, 2L, 3L)))
