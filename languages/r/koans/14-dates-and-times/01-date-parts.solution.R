d <- as.Date("2026-10-16")
test_that("format picks parts out", expect_equal(format(d, "%d/%m/%Y"), "16/10/2026"))
test_that("weekdays names the day", expect_equal(weekdays(d), "Friday"))
test_that("months names the month", expect_equal(months(d), "October"))
lt <- as.POSIXlt(d)
test_that("POSIXlt counts years from 1900", expect_equal(lt$year, 126))
test_that("with January as 0", expect_equal(lt$mon, 9))
test_that("yday counts the days from 0 too", expect_equal(lt$yday, 288))
test_that("as.Date reads other formats", expect_equal(as.Date("16 Oct 2026", format = "%d %b %Y"), d))
